CREATE TABLE IF NOT EXISTS Features (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isChanged BOOLEAN,
    type INT,
    seatPitch DOUBLE,
    seatWidth DOUBLE,
    newSeatPitch DOUBLE,
    newSeatWidth DOUBLE,
    videoType VARCHAR(255),
    newVideoType VARCHAR(255),
    powerType VARCHAR(255),
    newPowerType VARCHAR(255),
    wifi VARCHAR(255),
    newWifi VARCHAR(255),
    specialFood VARCHAR(255),
    newSpecialFood VARCHAR(255),
    seatType VARCHAR(255),
    newSeatType VARCHAR(255),
    price INT,
    newPrice INT
);
 
CREATE TABLE IF NOT EXISTS Customers (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(255),
    email VARCHAR(255)
);
 
CREATE TABLE IF NOT EXISTS Flights (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    isChanged BOOLEAN,
    flightName VARCHAR(255),
    totalSeats INT,
    currentSeats INT,
    departureCity VARCHAR(255),
    arrivalCity VARCHAR(255),
    departureDate TIMESTAMP,
    arrivalDate TIMESTAMP,
    oldESeats INT,
    oldBSeats INT,
    oldFSeats INT,
    oldTSeats INT,
    economySeats INT,
    businessSeats INT,
    firstSeats INT
);
 
CREATE TABLE IF NOT EXISTS Seats (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    seatNumber INT,
    customerEmail VARCHAR(255),
    featureType VARCHAR(255),
    flightName VARCHAR(255)
);
 
CREATE TABLE IF NOT EXISTS Cities (
    ID BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cityName VARCHAR(255)
);